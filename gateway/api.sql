-- api.authorize_local ---------------------------------------------------------
--------------------------------------------------------------------------------
/**
 * @brief api.authorize for a pooled connection: the session context lives
 *        ONLY until the end of the current transaction.
 *
 * The platform's session context is nine `current.*` GUCs written with
 * set_config(…, false) — session-scoped, they survive COMMIT and are reset only
 * by the next SessionIn (skill, "Context and session"). That is right for the
 * C++ workers, which own a connection per request, and wrong for a Go module
 * behind pgx / pgbouncer in transaction mode: the next transaction on the same
 * backend would inherit the previous caller's identity. track-a-graftio.md §4
 * asks for SessionIn(pLocal); until SessionIn carries that parameter this
 * wrapper gives the same guarantee from the outside: it authorises through
 * Authorize, then moves every context GUC it set from the session level to the
 * transaction level — session value cleared to '' (GetVar reads '' as NULL),
 * the value re-set with is_local = true. After COMMIT or ROLLBACK the backend
 * carries no identity. The pool's RESET ALL on return is the second layer, not
 * the first.
 *
 * Contract К7: `sub` of the JWT is the session code; agent = User-Agent,
 * host = X-Forwarded-For. authorized = false → 401 with `message`.
 *
 * @param {varchar} pSession - Session code (JWT sub)
 * @param {text} pAgent - User-Agent
 * @param {inet} pHost - Client address
 * @return {record} authorized, userid, message — same shape as api.authorize
 * @since 1.2.21
 */
CREATE OR REPLACE FUNCTION api.authorize_local (
  pSession          varchar,
  pAgent            text DEFAULT null,
  pHost             inet DEFAULT null,
  OUT authorized    boolean,
  OUT userid        uuid,
  OUT message       text
) RETURNS           record
AS $$
DECLARE
  vName             text;
  vValue            text;
BEGIN
  authorized := Authorize(pSession, pAgent, pHost);
  userid := current_userid();
  message := GetErrorMessage();

  FOREACH vName IN ARRAY ARRAY['session', 'user', 'client_id', 'access', 'notification', 'area', 'oper_date', 'debug', 'log']
  LOOP
    vValue := current_setting('current.' || vName, true);
    IF vValue IS NOT NULL THEN
      PERFORM set_config('current.' || vName, '', false);
      PERFORM set_config('current.' || vName, vValue, true);
    END IF;
  END LOOP;
END;
$$ LANGUAGE plpgsql
   SECURITY DEFINER
   SET search_path = kernel, pg_temp;

GRANT EXECUTE ON FUNCTION api.authorize_local(varchar, text, inet) TO apibot;

