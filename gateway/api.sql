-- api.log_request -------------------------------------------------------------
--------------------------------------------------------------------------------
/**
 * @brief Journals one /api/v2 request into db.api_log the way api.run journals
 *        /api/v1 (track-a-graftio.md §4): AddApiLog — which a configuration may
 *        override with its own redaction list — plus the server-side runtime and
 *        the HTTP status, so a v2 line reads like a v1 line in the same table.
 *
 *        Call it at the END of the request, inside the same transaction as the
 *        work (the identity comes from the transaction-local context set by
 *        api.authorize_local): pRuntime is what the module measured, pStatus
 *        what it is about to answer. The request id (contract К7,
 *        X-Request-Id) and the method travel in `json` under "_request", next
 *        to the payload, because db.api_log has no column for either and a
 *        column is a platform change.
 *
 *        A refusal is a line too (1.2.24, go-platform T185): the module rolls
 *        the work back to a savepoint and calls this in the same transaction,
 *        or — when the refusal aborted the transaction before any savepoint —
 *        in a fresh one, with no session context at all. Nothing here needs a
 *        session: AddApiLog leaves `session` and `username` empty when
 *        current_session() names none. pError carries the catalogue code of
 *        the refusal (ERR-400-001, …) under "_request.error", so that a 4xx
 *        line says what was refused, not only that it was.
 *
 * @param {text} pMethod - HTTP method
 * @param {text} pPath - Request path as received (/api/v2/…)
 * @param {jsonb} pPayload - Request body (or query as an object); redacted by AddApiLog
 * @param {integer} pStatus - HTTP status the module answers with
 * @param {interval} pRuntime - Server-side duration measured by the module
 * @param {uuid} pRequestId - X-Request-Id generated by the gateway
 * @param {text} pError - Catalogue code of the error answered (NULL on success)
 * @return {bigint} db.api_log.id
 * @since 1.2.21
 */
CREATE OR REPLACE FUNCTION api.log_request (
  pMethod       text,
  pPath         text,
  pPayload      jsonb DEFAULT null,
  pStatus       integer DEFAULT null,
  pRuntime      interval DEFAULT null,
  pRequestId    uuid DEFAULT null,
  pError        text DEFAULT null
) RETURNS       bigint
AS $$
DECLARE
  nId           bigint;
BEGIN
  nId := AddApiLog(pPath, coalesce(pPayload, '{}'::jsonb)
                          || jsonb_build_object('_request', jsonb_strip_nulls(jsonb_build_object(
                               'method', pMethod, 'status', pStatus, 'id', pRequestId, 'error', pError))));

  IF pRuntime IS NOT NULL THEN
    UPDATE db.api_log SET runtime = pRuntime WHERE id = nId;
  END IF;

  RETURN nId;
END;
$$ LANGUAGE plpgsql
   SECURITY DEFINER
   SET search_path = kernel, pg_temp;

GRANT EXECUTE ON FUNCTION api.log_request(text, text, jsonb, integer, interval, uuid, text) TO apibot;

